# 交互版复利计算器（升级自固定参数版本）
# 复利公式：最终金额 = 本金 × (1 + 年利率) ^ 年数

principal = float(input("请输入本金（元）："))               # 本金 P，用户输入
rate = float(input("请输入年利率（如 5 表示 5%）：")) / 100   # 年利率，百分数转小数：5 → 0.05

years = 3  # 存款年限固定为 3 年，每年复利 1 次

# 输入检查：本金必须大于 0，年利率不能为负数
if principal <= 0:
    print("本金必须大于 0")       # 本金不合法，提示后不计算
elif rate < 0:
    print("年利率不能为负数")     # 负利率不合法，提示后不计算
else:
    # 复利计算：每年本金变为上一年的 (1 + 年利率) 倍，共滚存 3 年
    final_amount = principal * (1 + rate) ** years
    # 输出最终本息和，保留两位小数
    print(f"最终本息和：{final_amount:.2f} 元")
