# 复利计算器（可交互输入版）
# 复利公式：最终本息和 = 本金 × (1 + 年利率) ** 年数

# 输入本金：最初存入的钱（元）
principal = float(input("请输入本金（元）："))

# 输入年利率：5% 写成 5，程序内部会除以 100 转成 0.05
# 因为 Python 中 % 是取余运算符,不是百分号,所以利率必须用小数参与运算
# 利率不能为负：若输入负数则提示"利率不能为负"并要求重新输入
while True:
    rate = float(input("请输入年利率（如 5 表示 5%）：")) / 100
    if rate < 0:
        print("利率不能为负")
    else:
        break

# 对比表：年限 10/20/30 年三行,列输出「复利终值 / 单利终值 / 差额」
# 复利终值 = 本金 × (1 + 年利率) ** 年数（利滚利,上一年利息会并入本金继续生息）
# 单利终值 = 本金 × (1 + 年利率 × 年数)（每年利息只按原始本金计算,利息不滚存）
# 差额     = 复利终值 - 单利终值（复利比单利多赚的钱）
print("年限 | 复利终值        | 单利终值        | 差额")
for years in (10, 20, 30):
    compound = principal * (1 + rate) ** years   # 复利终值：利滚利
    simple = principal * (1 + rate * years)     # 单利终值：利息不滚存
    diff = compound - simple                     # 差额：复利比单利多赚的部分
    print(f"{years:>4} | {round(compound, 2):<14} | {round(simple, 2):<14} | {round(diff, 2)}")
